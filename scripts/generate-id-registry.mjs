import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const manifest = JSON.parse(readFileSync(resolve(root, "package.json"), "utf8"));

function keyFor(id) {
  return id
    .replace(/^cInsight\./, "")
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/[.-]/g, "_")
    .toUpperCase();
}

function objectLiteral(name, ids) {
  const entries = ids.map((id) => `  ${keyFor(id)}: ${JSON.stringify(id)},`);
  return `export const ${name} = {\n${entries.join("\n")}\n} as const;`;
}

const commandIds = manifest.contributes.commands.map(({ command }) => command);
const viewIds = Object.values(manifest.contributes.views)
  .flat()
  .map(({ id }) => id);

const source = `// Generated by scripts/generate-id-registry.mjs. Do not edit manually.

${objectLiteral("COMMANDS", commandIds)}

export const INTERNAL_COMMANDS = {
  PREVIEW_LOCATION: "cInsight.previewLocation",
  ACTIVATE_TREE_LOCATION: "cInsight.activateTreeLocation",
  REFERENCES_FOCUS: "cInsight.references.focus",
  CALLERS_FOCUS: "cInsight.callers.focus",
  CALLEES_FOCUS: "cInsight.callees.focus",
  STATUS_FOCUS: "cInsight.status.focus",
  SUPERTYPES_FOCUS: "cInsight.supertypes.focus",
  SUBTYPES_FOCUS: "cInsight.subtypes.focus",
  INCLUDES_FOCUS: "cInsight.includes.focus",
  INCLUDED_BY_FOCUS: "cInsight.includedBy.focus",
} as const;

${objectLiteral("VIEWS", viewIds)}

export const CONTEXT_KEYS = {
  ACTIVE: "cInsight.active",
  CONTEXT_PINNED: "cInsight.pinned",
  PREVIEW_LOCKED: "cInsight.previewLocked",
  REFERENCES_PINNED: "cInsight.referencesPinned",
  CALL_HIERARCHY_PINNED: "cInsight.callHierarchyPinned",
} as const;

export type CommandId =
  | (typeof COMMANDS)[keyof typeof COMMANDS]
  | (typeof INTERNAL_COMMANDS)[keyof typeof INTERNAL_COMMANDS];
export type ViewId = (typeof VIEWS)[keyof typeof VIEWS];
`;

const target = resolve(root, "src/ids.ts");
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== source) {
    console.error("src/ids.ts is stale; run npm run ids:generate.");
    process.exitCode = 1;
  }
} else {
  writeFileSync(target, source);
}
